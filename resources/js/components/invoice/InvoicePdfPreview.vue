<script setup lang="ts">
import type { PDFDocumentLoadingTask, RenderTask } from 'pdfjs-dist';
import { computed, nextTick, onBeforeUnmount, ref, watch } from 'vue';
import { api, apiUrl } from '@/api/client';
import FullScreenSheet from '@/components/ui/FullScreenSheet.vue';
import Icon from '@/components/ui/Icon.vue';
import SecondaryButton from '@/components/ui/SecondaryButton.vue';
import { useBreakpoint } from '@/composables/useBreakpoint';
import { useCurrentProfile } from '@/composables/useCurrentProfile';
import { t } from '@/i18n';
import { loadPdf } from '@/utils/pdf';

/**
 * Перегляд PDF: the invoice's PDF in the app, whatever its status, every page drawn with pdf.js at the width of its
 * column. A draft generated by PryTax is rendered as its freeze would print it now, marked as a draft across every
 * page and stored nowhere, with a note that its number and content may still change; any other invoice shows its own
 * document, which «Завантажити PDF» downloads. «Відкрити PDF» opens it in the browser's (or the desktop app's) own
 * viewer, to zoom or print it. On desktop it is the wide dialog, the pages about 760 px wide on grey.
 */
const { invoiceId, draft, number = null } = defineProps<{
    invoiceId: number;
    /** A draft generated by PryTax: its preview is marked as a draft, and there is nothing to download yet. */
    draft: boolean;
    /** The invoice's number, or the one the draft would get. */
    number?: string | null;
}>();
const open = defineModel<boolean>('open', { required: true });

const { path } = useCurrentProfile();
const { isDesktop } = useBreakpoint();

const column = ref<HTMLElement | null>(null);
const pageCount = ref(0);
const loading = ref(false);
const failed = ref(false);
const pdfUrl = ref<string | null>(null);

const subtitle = computed(() => (draft
    ? t('invoices.pdfPreview.draftSubtitle', { number: number ?? '—' })
    : number ?? undefined));
const downloadUrl = computed(() => apiUrl(path(`invoices/${invoiceId}/pdf`)));

let controller: AbortController | null = null;
let task: PDFDocumentLoadingTask | null = null;
let rendering: RenderTask | null = null;

watch(open, (isOpen) => {
    if (isOpen) {
        void load();
    } else {
        forget();
    }
});

function forget(): void {
    controller?.abort();
    rendering?.cancel();
    rendering = null;
    void task?.destroy();
    task = null;
    pageCount.value = 0;

    if (pdfUrl.value) {
        URL.revokeObjectURL(pdfUrl.value);
        pdfUrl.value = null;
    }
}

/**
 * Fetch the preview's PDF and draw its pages one after another at the width of the column; closing (or a retry)
 * cancels the drawing, as pdf.js draws on a canvas once at a time.
 */
async function load(): Promise<void> {
    forget();
    const current = new AbortController();
    controller = current;
    loading.value = true;
    failed.value = false;

    try {
        const blob = await api.blob(path(`invoices/${invoiceId}/preview`), undefined, current.signal);
        const opened = await loadPdf(blob);
        const document = await opened.promise;

        if (current.signal.aborted) {
            await opened.destroy();

            return;
        }

        task = opened;
        pdfUrl.value = URL.createObjectURL(blob);
        pageCount.value = document.numPages;
        loading.value = false;
        await nextTick();

        const canvases = [...(column.value?.querySelectorAll('canvas') ?? [])];
        const width = column.value?.clientWidth ?? 358;

        for (const [index, canvas] of canvases.entries()) {
            const page = await document.getPage(index + 1);

            if (current.signal.aborted) {
                return;
            }

            const viewport = page.getViewport({ scale: (width / page.getViewport({ scale: 1 }).width) * (window.devicePixelRatio || 1) });
            canvas.width = Math.floor(viewport.width);
            canvas.height = Math.floor(viewport.height);
            rendering = page.render({ canvas, viewport });
            await rendering.promise;
        }

        rendering = null;
    } catch {
        if (!current.signal.aborted) {
            failed.value = true;
            loading.value = false;
        }
    }
}

function openInViewer(): void {
    if (pdfUrl.value) {
        window.open(pdfUrl.value, '_blank', 'noopener');
    }
}

onBeforeUnmount(forget);
</script>

<template>
    <FullScreenSheet v-model:open="open" :title="t('invoices.pdfPreview.title')" :subtitle="subtitle" dismiss="close" :size="isDesktop ? 'wide' : 'default'">
        <div :class="isDesktop ? 'scrollbar-thin min-h-0 flex-1 overflow-y-auto bg-muted px-8 py-6' : 'contents'">
            <div class="mx-auto flex w-full flex-col gap-4" :class="isDesktop ? 'max-w-190' : ''">
                <p v-if="draft" class="m-0 rounded-card bg-warning-soft px-4 py-3 text-14 leading-normal text-ink-2">{{ t('invoices.pdfPreview.draftNote') }}</p>

                <div ref="column" :aria-busy="loading ? 'true' : 'false'" class="flex flex-col gap-4">
                    <div v-if="loading" class="aspect-[210/297] w-full animate-pulse rounded-[4px] bg-muted" role="status" :aria-label="t('core.common.loading')" />
                    <div v-else-if="failed" class="flex aspect-[210/297] w-full flex-col items-center justify-center gap-3 rounded-[4px] bg-surface p-6 text-center">
                        <span class="text-15 text-ink-2">{{ t('invoices.pdfPreview.failed') }}</span>
                        <button type="button" class="min-h-11 px-3 text-15 font-medium text-accent" @click="load">{{ t('core.common.retry') }}</button>
                    </div>
                    <div
                        v-for="page in pageCount"
                        v-else
                        :key="page"
                        class="aspect-[210/297] w-full overflow-hidden rounded-[4px] bg-white shadow-[0_2px_12px_rgb(23_25_31/0.12)]"
                    >
                        <canvas class="block h-full w-full" />
                    </div>
                </div>
            </div>
        </div>

        <template #footer>
            <div class="grid gap-2.5" :class="[draft ? 'grid-cols-1' : 'grid-cols-[1fr_1.4fr]', isDesktop ? 'ml-auto w-120' : '']">
                <SecondaryButton :disabled="!pdfUrl" @click="openInViewer">
                    {{ t('invoices.document.openPdf') }}
                    <Icon name="external" :size="18" />
                </SecondaryButton>
                <a
                    v-if="!draft"
                    :href="downloadUrl"
                    download
                    class="flex h-13 w-full items-center justify-center gap-2 rounded-button bg-accent text-16 font-semibold text-white no-underline hover:bg-accent-hover hover:text-white"
                >
                    <Icon name="download" :size="20" />
                    {{ t('invoices.detail.downloadPdf') }}
                </a>
            </div>
        </template>
    </FullScreenSheet>
</template>
