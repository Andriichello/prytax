<script setup lang="ts">
import { computed, onBeforeUnmount, ref, watch } from 'vue';
import { api, apiUrl } from '@/api/client';
import FullScreenSheet from '@/components/ui/FullScreenSheet.vue';
import Icon from '@/components/ui/Icon.vue';
import PdfPages from '@/components/ui/PdfPages.vue';
import SecondaryButton from '@/components/ui/SecondaryButton.vue';
import { useBreakpoint } from '@/composables/useBreakpoint';
import { useCurrentProfile } from '@/composables/useCurrentProfile';
import { t } from '@/i18n';

/**
 * Перегляд PDF: the invoice's PDF in the app, whatever its status, every page drawn at the width of its column (about
 * 760 px on desktop), with the zoom over it (`PdfPages`). A draft generated by PryTax is rendered as its freeze would
 * print it now, marked as a draft across every page and stored nowhere, with a note that its number and content may
 * still change; any other invoice shows its own document, which «Завантажити PDF» downloads. «Відкрити PDF» opens it
 * in the browser's (or the desktop app's) own viewer, to print it. On desktop it is the wide dialog, the pages on grey.
 */
const { invoiceId, draft, number = null } = defineProps<{
    invoiceId: number;
    /** A draft generated by PryTax: its preview is marked as a draft, and there is nothing to download yet. */
    draft: boolean;
    /** The invoice's number, or the one the draft would get. */
    number?: string | null;
}>();
const open = defineModel<boolean>('open', { required: true });

const { path } = useCurrentProfile();
const { isDesktop } = useBreakpoint();

const blob = ref<Blob | null>(null);
const loading = ref(false);
const failed = ref(false);
const pdfUrl = ref<string | null>(null);

const subtitle = computed(() => (draft
    ? t('invoices.pdfPreview.draftSubtitle', { number: number ?? '—' })
    : number ?? undefined));
const downloadUrl = computed(() => apiUrl(path(`invoices/${invoiceId}/pdf`)));

let controller: AbortController | null = null;

watch(open, (isOpen) => {
    if (isOpen) {
        void load();
    } else {
        forget();
    }
});

function forget(): void {
    controller?.abort();
    blob.value = null;

    if (pdfUrl.value) {
        URL.revokeObjectURL(pdfUrl.value);
        pdfUrl.value = null;
    }
}

/** Fetch the preview's PDF, which `PdfPages` draws. */
async function load(): Promise<void> {
    forget();
    const current = new AbortController();
    controller = current;
    loading.value = true;
    failed.value = false;

    try {
        const fetched = await api.blob(path(`invoices/${invoiceId}/preview`), undefined, current.signal);
        blob.value = fetched;
        pdfUrl.value = URL.createObjectURL(fetched);
    } catch {
        if (!current.signal.aborted) {
            failed.value = true;
        }
    } finally {
        if (!current.signal.aborted) {
            loading.value = false;
        }
    }
}

function openInViewer(): void {
    if (pdfUrl.value) {
        window.open(pdfUrl.value, '_blank', 'noopener');
    }
}

onBeforeUnmount(forget);
</script>

<template>
    <FullScreenSheet v-model:open="open" :title="t('invoices.pdfPreview.title')" :subtitle="subtitle" dismiss="close" :size="isDesktop ? 'wide' : 'default'">
        <PdfPages
            class="flex-1"
            :class="isDesktop ? 'bg-muted' : ''"
            :inset="isDesktop ? 'px-8 py-6' : ''"
            :max-fit-width="760"
            :blob="blob"
            :loading="loading"
            :failed="failed"
            @retry="load"
            @failed="failed = true"
        >
            <p v-if="draft" class="mx-auto mt-0 mb-4 max-w-190 rounded-card bg-warning-soft px-4 py-3 text-14 leading-normal text-ink-2">
                {{ t('invoices.pdfPreview.draftNote') }}
            </p>
            <template #failed>{{ t('invoices.pdfPreview.failed') }}</template>
        </PdfPages>

        <template #footer>
            <div class="grid gap-2.5" :class="[draft ? 'grid-cols-1' : 'grid-cols-[1fr_1.4fr]', isDesktop ? 'ml-auto w-120' : '']">
                <SecondaryButton :disabled="!pdfUrl" @click="openInViewer">
                    {{ t('invoices.document.openPdf') }}
                    <Icon name="external" :size="18" />
                </SecondaryButton>
                <a
                    v-if="!draft"
                    :href="downloadUrl"
                    download
                    class="flex h-13 w-full items-center justify-center gap-2 rounded-button bg-accent text-16 font-semibold text-white no-underline hover:bg-accent-hover hover:text-white"
                >
                    <Icon name="download" :size="20" />
                    {{ t('invoices.detail.downloadPdf') }}
                </a>
            </div>
        </template>
    </FullScreenSheet>
</template>
